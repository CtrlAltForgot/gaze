import {Parties} from './party.js';
import path from 'node:path';
import fs from 'node:fs';
import {pathToFileURL} from 'node:url';
import {Store} from './store.js';
import {Jellyfin} from './jellyfin.js';
import {Spotify} from './spotify.js';
import {Worker} from './worker.js';
import {downloadAudio} from './audio.js';
import {createServer} from './http.js';
import {ArtworkSearch,ArtworkWorker} from './artwork.js';
import {ArtistArtworkWorker} from './artist-artwork.js';
import {createSynoptiResolver} from './synopti-resolver.js';
const directory=process.env.GAZE_DATA||'/gaze-data',musicRoot=process.env.GAZE_MUSIC||'/music';
if(!process.env.JELLYFIN_URL)throw Error('Set JELLYFIN_URL before starting gaze.');
fs.mkdirSync(directory,{recursive:true});fs.mkdirSync(musicRoot,{recursive:true});
const {playable,scoreSpotifyCandidate,ytArgs}=await import(pathToFileURL(path.join(process.env.SYNOPTI_MODULE_ROOT||'/app/src','music.js')));
const {spotifyApiJson}=await import(pathToFileURL(path.join(process.env.SYNOPTI_MODULE_ROOT||'/app/src','spotify-api.js')));
const store=new Store(directory),jellyfin=new Jellyfin(process.env.JELLYFIN_URL,{musicPath:process.env.JELLYFIN_MUSIC_PATH||'/data/music/gaze Imports'}),spotify=new Spotify({directory,sharedFile:process.env.SYNOPTI_SPOTIFY_FILE||'/synopti-data/spotify-auth.json',api:spotifyApiJson});
const feedDirectory=process.env.SYNOPTI_FEED||'/synopti-data/gaze-events';
const worker=new Worker({store,jellyfin,spotify,resolve:createSynoptiResolver({playable,scoreSpotifyCandidate,ytArgs}),download:job=>downloadAudio(job,{directory,musicRoot}),feedDirectory,guildId:process.env.SYNOPTI_GUILD_ID,settingsFile:process.env.SYNOPTI_SETTINGS||'/synopti-data/settings.json'});
const artwork=new ArtworkWorker({store,jellyfin,search:new ArtworkSearch({directory:path.join(directory,'artwork-staging'),...(process.env.GAZE_ARTWORK_USER_AGENT?{userAgent:process.env.GAZE_ARTWORK_USER_AGENT}:{})})});
const artistArtwork=new ArtistArtworkWorker({store,jellyfin,search:new ArtworkSearch({directory:path.join(directory,'artwork-staging')})});
const parties=new Parties({jellyfin,publicOrigin:process.env.GAZE_PUBLIC_ORIGIN,guests:process.env.GAZE_PARTY_GUESTS==='true'});
const partyTimer=setInterval(()=>parties.prune(),5000);
const server=createServer({store,jellyfin,spotify,worker,feedDirectory,artwork,parties});
server.listen(Number(process.env.GAZE_PORT||8097),process.env.GAZE_BIND||'0.0.0.0',()=>console.log('gaze service ready.'));
const timer=setInterval(()=>worker.tick().catch(()=>console.error('gaze background sync needs review.')),2000);
const artworkTimer=setInterval(()=>artwork.tick().catch(()=>console.error('gaze artwork search needs review.')),2000);
const artistTimer=setInterval(()=>artistArtwork.tick().catch(()=>console.error('gaze artist artwork needs review.')),500);
process.on('SIGTERM',()=>{clearInterval(partyTimer);for(const id of parties.sessions.keys())parties.end(id);clearInterval(timer);clearInterval(artworkTimer);clearInterval(artistTimer);server.close(()=>process.exit(0));});
